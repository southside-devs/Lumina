# ── Step 1: Create Tables & Columns ──────────────────────────────────────────

def get_existing_tables():
    """Return {table_name: table_id} for tables that already exist."""
    try:
        result = api_get("/table")
        return {t["table_name"]: t["table_id"] for t in result.get("data", [])}
    except Exception as e:
        log(f"Could not list existing tables: {e}", "WARN")
        return {}


def provision_tables():
    print("\n► STEP 1 — Creating Data Store tables\n")
    existing = get_existing_tables()

    for table_name in TABLE_ORDER:
        columns = SCHEMA[table_name]

        if table_name in existing:
            log(f"{table_name} — already exists, skipping", "WARN")
            continue

        try:
            print(f"\n  Creating: {table_name}")
            result = api_post("/table", {"table_name": table_name})
            table_id = result["data"]["table_id"]
            log(f"Table created (ID: {table_id})")

            for col_name, data_type, mandatory in columns:
                try:
                    api_post(f"/table/{table_id}/column", {
                        "column_name":   col_name,
                        "data_type":     data_type,
                        "is_mandatory":  mandatory,
                        "is_searchable": True,
                    })
                    flag = " [required]" if mandatory else ""
                    log(f"  + {col_name:<25} {data_type}{flag}")
                    time.sleep(0.2)
                except Exception as e:
                    log(f"  Column {col_name} failed: {e}", "ERROR")

        except Exception as e:
            log(f"Failed to create {table_name}: {e}", "ERROR")

        time.sleep(0.5)

    print("\n  ✔ All tables created.\n")


# ── Step 2: Seed Data from CSVs ───────────────────────────────────────────────

def _is_number(val):
    try:
        float(str(val))
        return True
    except (ValueError, TypeError):
        return False


def seed_table(table_name, csv_path):
    if not csv_path.exists():
        log(f"CSV not found: {csv_path.name} — skipping {table_name}", "WARN")
        return 0

    valid_cols = [col[0] for col in SCHEMA[table_name]]
    inserted = failed = 0

    with open(csv_path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    log(f"Seeding {table_name}: {len(rows)} rows ...")

    for i, row in enumerate(rows):
        try:
            cols, vals = [], []
            for col in valid_cols:
                v = row.get(col, "")
                if v in (None, "", "nan", "NaN"):
                    continue
                cols.append(col)
                vals.append(str(v) if _is_number(v) else f"'{str(v).replace(chr(39), chr(39)+chr(39))}'")

            if not cols:
                continue

            query = f"INSERT INTO {table_name} ({', '.join(cols)}) VALUES ({', '.join(vals)})"
            api_post("/zcql", {"query": query})
            inserted += 1

            if (i + 1) % 200 == 0:
                log(f"  {i + 1}/{len(rows)} rows done...")

            time.sleep(0.05)   # ~20 inserts/sec

        except Exception as e:
            failed += 1
            if failed <= 3:
                log(f"  Row {i+1} failed: {e}", "WARN")

    log(f"  ✔ {table_name}: {inserted} inserted, {failed} failed")
    return inserted


def seed_all():
    print("\n► STEP 2 — Seeding tables with synthetic data\n")

    if not CSV_DIR.exists():
        log(
            f"CSV directory not found: {CSV_DIR}\n"
            "  Run the synthetic data generator first:\n"
            "  python data/generator/generate_synthetic_data.py",
            "WARN"
        )
        return

    total = 0
    for table_name in TABLE_ORDER:
        total += seed_table(table_name, CSV_DIR / CSV_MAP[table_name])
        time.sleep(1)

    print(f"\n  Total rows inserted: {total}")


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    print("\n" + "=" * 60)
    print("  Lumina — Catalyst Data Store Provisioner")
    print("=" * 60)

    validate_config()

    print(f"\n  Project ID : {PROJECT_ID}")
