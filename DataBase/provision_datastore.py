# ── CONFIG ────────────────────────────────────────────────────────────────────
# Edit these OR set as environment variables before running.

PROJECT_ID   = os.environ.get("CATALYST_PROJECT_ID", "")
ACCESS_TOKEN = os.environ.get("CATALYST_ACCESS_TOKEN", "")
ZOHO_DOMAIN  = os.environ.get("ZOHO_DOMAIN", "zoho.com")   # zoho.in / zoho.eu also valid

# Set to "false" to skip seeding data after table creation
SEED_DATA    = os.environ.get("SEED_DATA", "true").lower() == "true"

